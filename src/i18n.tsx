export function localizeValue(language: Language, value: unknown) {
  const raw = String(value ?? "").trim();
  const key = valueKeys[raw.toUpperCase()];
  return key ? translate(language, key) : raw.replaceAll("_", " ");
}

export function localizeReason(language: Language, value: unknown) {
  const raw = String(value ?? "").trim();
  if (!raw) return "—";
  const [code, ...noteParts] = raw.split(" · ");
  const coded: Record<string, Key> = {
    SUPPLIER_DELIVERY: "supplierDelivery",
    DAMAGED_GOODS: "damagedGoods",
    INVENTORY_COUNT: "inventoryCount",
    CORRECTION: "correction",
  };
  if (coded[code]) {
    const label = translate(language, coded[code]);
    return noteParts.length ? `${label} · ${noteParts.join(" · ")}` : label;
  }
  const exact: Record<string, Key> = {
    "Initial stock": "initialStockReason",
    "Manual stock update": "manualStockReason",
    "Product management update": "productManagementReason",
  };
  if (exact[raw]) return translate(language, exact[raw]);
  if (raw.startsWith("POS sale"))
    return `${translate(language, "posSaleReason")} ${raw.slice("POS sale".length).trim()}`.trim();
  return raw;
}

